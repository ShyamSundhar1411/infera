export const getAlgorithms = (): Algorithm[] =>
  ALGORITHMS.map((meta) => ({ ...meta, content: CONTENT[meta.slug] }));

export const getAlgorithm = (slug: string): Algorithm | undefined =>
  getAlgorithms().find((a) => a.slug === slug);

export const getAlgorithmsByCategory = (category: CategoryId) =>
  getAlgorithms().filter((a) => a.category === category);

export const getDefaultParams = (meta: AlgorithmMeta) =>
  Object.fromEntries(meta.params.map((p) => [p.key, p.default]));
